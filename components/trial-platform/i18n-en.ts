/** Arabic → English; text that has no entry comes back unchanged. */
export function toEn(text: string): string {
  const core = text.trim();
  if (!core) return text;
  let out = EXACT[core];
  if (out === undefined) {
    for (const [re, tpl] of PATTERNS) {
      const m = re.exec(core);
      if (!m) continue;
      out = tpl.replace(/\{\$(\d)\}|\$(\d)/g, (_, tr, raw) => (tr ? toEn(m[Number(tr)]) : m[Number(raw)]));
      break;
    }
  }
  if (out === undefined) return text;
  const start = text.indexOf(core);
  return text.slice(0, start) + out + text.slice(start + core.length);
}

const TEXT_PROPS = ["aria-label", "placeholder", "title"] as const;

/** A copy of the element tree with every text node and label passed through `tr`. */
export function localize(node: ReactNode, tr: (s: string) => string): ReactNode {
  if (typeof node === "string") return tr(node);
  if (Array.isArray(node)) return node.map((n) => localize(n, tr));
  if (!isValidElement(node)) return node;

  const props = node.props as Record<string, unknown>;
  const next: Record<string, unknown> = {};
  for (const p of TEXT_PROPS) {
    if (typeof props[p] === "string") next[p] = tr(props[p] as string);
  }
  const kids = props.children;
  if (kids === undefined || kids === null) return Object.keys(next).length ? cloneElement(node, next) : node;
  // children written side by side in the markup are passed back one by one, so they stay keyless
  return Array.isArray(kids)
    ? cloneElement(node, next, ...kids.map((k) => localize(k, tr)))
    : cloneElement(node, next, localize(kids as ReactNode, tr));
}
